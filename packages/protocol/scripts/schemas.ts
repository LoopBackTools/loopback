/**
 * Generates the Effect schemas readers decode the contract with, one module per revision, from the
 * OpenAPI document `tsp compile` emits for each. Run by `pnpm generate`, after the compile.
 *
 * Three things are done on the way, each because readers need it:
 *
 * - Objects the spec seals (`unevaluatedProperties: false`, which Effect can't import) are handed to
 *   the generator as `additionalProperties: false`, which it reads as a plain struct. A plain struct
 *   ignores fields it doesn't know, which is what a reader on an older revision must do.
 * - Every schema in the contract is generated, the socket frames and MCP inputs included, not only
 *   those an HTTP route reaches.
 * - Each union a release can grow ends in a member that reads what this revision can't
 *   (`src/unknown.ts`), so one message of a newer kind doesn't fail everything around it.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as Generator from "@effect/openapi-generator/JsonSchemaGenerator";
import type * as JsonSchema from "effect/JsonSchema";

const root = join(import.meta.dirname, "..");

/** The name of the synthetic schema that makes the generator emit every other one. */
const ROOT = "LoopbackContractRoot";

/** Each union a release can grow: the member that reads what it can't, and that member's type. */
const GROWABLE: Readonly<Record<string, { readonly member: string; readonly type: string }>> = {
	Ask: { member: "unknownAsk(AskStatus)", type: "UnknownAsk<AskStatus>" },
	Block: { member: "unknownBlock", type: "UnknownBlock" },
	Reply: { member: "unknownReply", type: "UnknownReply" },
	ServerEvent: { member: "unknownEvent", type: "UnknownEvent" },
};

/** The document with every sealed object marked closed in the form the generator reads. */
const closed = (value: unknown): unknown => {
	if (Array.isArray(value)) return value.map(closed);
	if (typeof value !== "object" || value === null) return value;
	return Object.fromEntries(
		Object.entries(value).map(([key, inner]) =>
			key === "unevaluatedProperties" ? ["additionalProperties", inner] : [key, closed(inner)],
		),
	);
};

/** Replaces the one match of `pattern` in `code`, failing loudly if there isn't exactly one. */
const replaceOnce = (code: string, pattern: RegExp, replacement: string, what: string) => {
	const matches = code.match(new RegExp(pattern.source, `${pattern.flags}g`)) ?? [];
	if (matches.length !== 1) {
		throw new Error(`Expected one ${what} in the generated schemas, found ${matches.length}.`);
	}
	return code.replace(pattern, replacement);
};

const revisions = readdirSync(join(root, "openapi"))
	.flatMap((name) => /^openapi\.(\d+)\.json$/.exec(name)?.[1] ?? [])
	.map(Number)
	.toSorted((a, b) => a - b);

for (const revision of revisions) {
	const source = `openapi/openapi.${revision}.json`;
	const document = closed(JSON.parse(readFileSync(join(root, source), "utf8"))) as {
		components: { schemas: JsonSchema.Definitions };
	};
	const { schemas } = document.components;
	// The generator emits what its roots reach. One synthetic root that refers to every schema
	// reaches them all, each emitted once; the root itself is cut off below.
	const generator = Generator.make();
	generator.addSchema(ROOT, {
		type: "object",
		properties: Object.fromEntries(
			Object.keys(schemas).map((name) => [name, { $ref: `#/components/schemas/${name}` }]),
		),
	});
	const [definitions = "", roots = ""] = generator
		.generate("openapi-3.1", schemas, false)
		.split(/^\/\/ schemas$/m);
	if (roots.match(/^export const /gm)?.length !== 1 || !roots.includes(`export const ${ROOT} `)) {
		throw new Error(
			"Expected the generator to emit only the synthetic root after its definitions.",
		);
	}
	let code = definitions;
	for (const [name, { member, type }] of Object.entries(GROWABLE)) {
		code = replaceOnce(
			code,
			new RegExp(`^(export type ${name} = .*)$`, "m"),
			`$1 | ${type}`,
			`type ${name}`,
		);
		code = replaceOnce(
			code,
			new RegExp(`^(export const ${name} = Schema\\.Union\\(\\[)([^\\]]*)(\\]\\))`, "m"),
			`$1$2, ${member}$3`,
			`union ${name}`,
		);
	}
	writeFileSync(
		join(root, `src/generated/schemas.r${revision}.gen.ts`),
		[
			`// GENERATED by scripts/schemas.ts from ${source}. DO NOT EDIT.`,
			"// Regenerate with: pnpm generate",
			'import * as Schema from "effect/Schema";',
			"import {",
			"\ttype UnknownAsk,",
			"\ttype UnknownBlock,",
			"\ttype UnknownEvent,",
			"\ttype UnknownReply,",
			"\tunknownAsk,",
			"\tunknownBlock,",
			"\tunknownEvent,",
			"\tunknownReply,",
			'} from "../unknown.ts";',
			code,
		].join("\n"),
	);
}

const latest = revisions.at(-1);
writeFileSync(
	join(root, "src/generated/schemas.gen.ts"),
	[
		"// GENERATED by scripts/schemas.ts. DO NOT EDIT. Regenerate with: pnpm generate",
		"",
		"/** The contract's latest revision: the one this release writes. */",
		`export const REVISION = ${latest};`,
		"",
		"/** Every revision of the contract, oldest first. */",
		`export const REVISIONS = [${revisions.join(", ")}] as const;`,
		"",
		`export * from "./schemas.r${latest}.gen.ts";`,
		"",
	].join("\n"),
);
